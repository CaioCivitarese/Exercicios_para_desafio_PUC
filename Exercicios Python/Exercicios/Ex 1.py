# 1 - Crie três variáveis com três tipos de dados diferentes, respeitando
# sua sintaxe:

var1 = "Caio"
var2 = 19
var3 = 1.70

print(var1, type(var1))
print(var2, type(var2))
print(var3, type(var3))

# nome =  'Fernando'
# ano =  1987
# valor =  19.99
 
 
# Para declarar uma variável basta dar um nome para a mesma,
# seguido do operador de atribuição “ = “ e do conteúdo a ser atribuído
# para essa variável.
# A  forma  como  o  atributo  da  variável  é  escrita  fará  com  que  o
# interpretador  identifique  automaticamente  o  tipo  de  dado  em  questão.
# Nesse caso, para a variável nome temos uma string, da mesma forma para
# variável ano temos um int assim como para variável valor temos um dado
# atribuído do tipo float.
