# 26  -  Crie  uma  variável  com  valor  inicial  0,  enquanto  o  valor  dessa
# variável for igual ou menos que 10, exiba em tela o próprio valor da
# variável.  A  cada  execução  a  mesma  deve  ter  seu  valor  atualizado,
# incrementado em 1 unidade.

num1 = 0

while num1 <= 10:
    print(num1)
    num1 += 1

# var =  0
 
# while  var <=  10 :
#    print ( var )
#   var = var +  1
 
 
# Toda vez que se faz necessário repetir uma determinada instrução
# enquanto um determinado objetivo não é atingido, podemos realizar essa
# repetição por meio da estrutura de repetição while.
# Quando usamos while, definimos uma condição a ser alcançada ou
# validada, e para que a execução do código não entre em um loop infinito,
# também usamos nessa estrutura de código de uma variável de controle.
# Repare que declaramos nossa estrutura condicional definindo que
# enquanto o valor de var for igual ou menor que 10, é exibido em tela por
# meio de nossa função print( ) o valor de var, em seguida atualizamos o
# valor  de  var  somando  ao  seu  valor  atual  uma  unidade.  Dessa  forma  o
# processo se repetirá até que var tenha o valor 10, encerrando o processo
# nesse ponto já que a condição definida foi alcançada.
# O retorno será:
 
