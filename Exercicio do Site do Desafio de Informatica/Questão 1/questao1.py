# 1) Escreva um programa que leia uma string da entrada padrão e verifique se a string é um palíndromo, ignorando espaços em branco e a diferença entre maiúsculas e minúsculas.
# Se for um palíndromo, o programa deverá exibir na tela a palavra SIM; caso contrário, deverá exibir NÃO. Considere que a string conterá apenas letras, algarismos e espaços em branco.
# Definição de palíndromo: sequência de caracteres que pode ser lida da mesma forma de trás para frente quanto de frente para trás. Exemplos: 'osso', '1a2 A2A1'. Se, por exemplo, o programa ler a string 'Am1 1 m a', deverá exibir 'SIM'.
# Entrada: seu programa receberá da entrada padrão uma string.
# Saída: para a string de entrada, seu programa deve exibir 'SIM' se for um palíndromo ou 'NÃO', caso contrário.


