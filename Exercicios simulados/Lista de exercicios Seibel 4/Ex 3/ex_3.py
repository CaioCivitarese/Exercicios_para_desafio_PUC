#  3) Um dos primeiros exemplos conhecidos de criptografia foi usado por Júlio César.
# César precisava fornecer instruções escritas aos seus generais, mas não queria que seus inimigos interceptassem a mensagem. Como resultado, ele desenvolveu
# o que mais tarde ficou conhecido como Cifra de César.

# A ideia por trás desta cifra é simples, cada letra da mensagem original é deslocada em 3 lugares.
# Como resultado, A torna-se D, B torna-se E, C torna-se F, D torna-se G, etc.
# As últimas três letras do alfabeto são deslocadas para o início: X torna-se A, Y torna-se B e Z torna-se C. Caracteres não alfabéticos não são modificados pela cifra.

